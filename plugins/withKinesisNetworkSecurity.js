/**
 * Expo config plugin: Android network security policy for Kinesis.
 *
 * Kinesis servers use HTTPS certificates from a CA that each shop creates
 * locally (see deploy/README-tls.md). Android 7+ apps ignore user-installed
 * CAs unless they opt in, so this plugin generates
 * res/xml/network_security_config.xml that:
 *
 *   - blocks cleartext HTTP everywhere in release builds;
 *   - trusts only system CAs for every host, EXCEPT
 *   - the Kinesis server host(s), which additionally trust user-installed
 *     CAs (the shop's local CA).
 *
 * A user-installed CA therefore cannot intercept traffic to any other host
 * this app might contact.
 *
 * Debug builds get a separate policy (src/debug) that permits cleartext so
 * the development client can load JavaScript from Metro over HTTP.
 *
 * Hosts come from EXPO_PUBLIC_API_URL plus the optional comma-separated
 * KINESIS_TLS_HOSTS (for example "kinesis.local,192.168.1.10"), read at
 * prebuild time. Run `npx expo prebuild --clean` after changing them.
 */

const fs = require("fs");
const path = require("path");
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
} = require("expo/config-plugins");

const CONFIG_NAME = "network_security_config";

function kinesisHosts() {
  const hosts = new Set();
  const apiUrl = (process.env.EXPO_PUBLIC_API_URL || "").trim();

  if (apiUrl) {
    try {
      hosts.add(new URL(apiUrl).hostname);
    } catch {
      throw new Error(
        `withKinesisNetworkSecurity: EXPO_PUBLIC_API_URL is not a valid URL: ${apiUrl}`,
      );
    }
  }

  for (const host of (process.env.KINESIS_TLS_HOSTS || "").split(",")) {
    if (host.trim()) {
      hosts.add(host.trim().toLowerCase());
    }
  }

  for (const host of hosts) {
    if (!/^[a-z0-9.\-:\[\]]+$/i.test(host)) {
      throw new Error(`withKinesisNetworkSecurity: invalid host "${host}"`);
    }
  }

  return [...hosts];
}

function releasePolicy(hosts) {
  const domains = hosts
    .map((host) => `    <domain includeSubdomains="false">${host}</domain>`)
    .join("\n");

  const kinesisDomainConfig = hosts.length
    ? `
  <!-- Kinesis server: also trust the shop's locally installed CA. -->
  <domain-config cleartextTrafficPermitted="false">
${domains}
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </domain-config>`
    : "";

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withKinesisNetworkSecurity.js. Do not edit. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>${kinesisDomainConfig}
</network-security-config>
`;
}

function debugPolicy() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withKinesisNetworkSecurity.js. Debug builds only:
     cleartext is allowed so the dev client can reach Metro. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
      <certificates src="user" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;
}

function writeFile(filePath, contents) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents);
}

function withKinesisNetworkSecurity(config) {
  const hosts = kinesisHosts();

  config = withDangerousMod(config, [
    "android",
    async (modConfig) => {
      const appDirectory = path.join(
        modConfig.modRequest.platformProjectRoot,
        "app",
        "src",
      );

      writeFile(
        path.join(appDirectory, "main", "res", "xml", `${CONFIG_NAME}.xml`),
        releasePolicy(hosts),
      );

      writeFile(
        path.join(appDirectory, "debug", "res", "xml", `${CONFIG_NAME}.xml`),
        debugPolicy(),
      );

      return modConfig;
    },
  ]);

  return withAndroidManifest(config, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      modConfig.modResults,
    );

    application.$["android:networkSecurityConfig"] = `@xml/${CONFIG_NAME}`;

    // networkSecurityConfig takes precedence on API 24+; remove the legacy
    // flag so it cannot re-enable cleartext on older devices.
    delete application.$["android:usesCleartextTraffic"];

    return modConfig;
  });
}

module.exports = withKinesisNetworkSecurity;
